"""Этап M8: Overlay + SystemTray + Hotkey — приёмка.

Архитектура M8:
  • Overlay (ui/overlay.py) — маленькое `tk.Toplevel` поверх всех окон
    в углу экрана (OVERLAY_POSITION). alpha=0.85, без рамки, click-through
    (не перехватывает мышь — проверяется отдельным сценарием). Дублирует
    состояние ассистента из главного окна: Готов / Слышу / Говорите /
    Обрабатываю / Отвечаю / Дежурный.
  • SystemTray (ui/tray.py) — pystray-иконка в daemon-thread. Меню:
      ▸ «Включить ассистента» — wake_listener.enable() (закрывает Q3 плана:
        после голосового StopCommand это способ вернуть дежурный режим).
      ▸ «Открыть папку сессии» — Проводник на session.current_dir/base_dir.
      ▸ «Перезагрузить конфиг» — заглушка, пишет строку в лог.
      ▸ «Выход» — штатный shutdown (как закрытие окна по крестику).
  • HotkeyListener (ui/hotkey.py) — pynput GlobalHotKeys. WAKE_HOTKEY из
    config (дефолт Ctrl+Alt+S) → wake_listener.enable(). Работает
    глобально — даже когда окно свёрнуто или не в фокусе.

Запуск этого скрипта поднимает обычный UI (как `python main.py --mode ui`):
overlay и трей появляются автоматически. Проверяйте сценарии ниже.

Действия пользователя:

  СЦЕНАРИЙ A — Overlay виден и показывает состояние:
    • Оконце должно появиться в правом верхнем углу экрана (по умолчанию
      OVERLAY_POSITION="top_right"), полупрозрачное, всегда поверх.
    • Во время загрузки моделей: «⚙ Инициализация».
    • После готовности: «🟢 Готов».
    • Нажмите «🎤 Слушай» в главном окне:
      ожидаемо последовательно на overlay: 🎙 Говорите → 🧠 Обрабатываю
      → 🔊 Отвечаю → 🟢 Готов.
    • Нажмите «🛌 Дежурный: вкл» — overlay показывает «🛌 Дежурный: «шурочка»».

  СЦЕНАРИЙ B — Overlay не перехватывает клики (click-through):
    • Откройте любое окно (например, Проводник) и двигайте его так,
      чтобы заголовок оказался ПОД overlay'ем.
    • Кликните в область, визуально перекрытую overlay'ем: щелчок
      должен «провалиться» в окно под ним (Проводник получит клик).
    • На overlay нельзя кликнуть, и он не должен блокировать ввод.

  СЦЕНАРИЙ C — Tray иконка и меню:
    • В системном трее рядом с часами появилась зелёная иконка «Ш».
    • Правый клик по ней открывает меню из 4 пунктов.
    • «Открыть папку сессии» — открывается Проводник в ~/Shura
      (или в папке текущей сессии, если она уже создана командами).
    • «Перезагрузить конфиг» — в логах появляется строка-заглушка.

  СЦЕНАРИЙ D — Возврат wake-word из трея после StopCommand:
    • В главном окне нажмите «🛌 Дежурный: вкл».
    • Скажите: «Шурочка, закончи работу»
      ожидаемо: overlay → «🟢 Готов»; кнопка «🛌 Дежурный: выкл».
    • Правый клик по трею → «Включить ассистента».
      ожидаемо: в логах «дежурный режим включён»; overlay → «🛌 Дежурный…»;
      кнопка «🛌 Дежурный: вкл». Можно снова произнести wake-word.

  СЦЕНАРИЙ E — Возврат wake-word через hotkey:
    • Снова выключите дежурный режим (кнопкой или командой).
    • Сверните окно/кликните в любое другое приложение (окно Шурочки
      не в фокусе — это важно, проверяет глобальность hotkey).
    • Нажмите Ctrl+Alt+S (WAKE_HOTKEY из config).
      ожидаемо: дежурный режим включился (проверьте, вернув фокус —
      кнопка и overlay показывают «вкл»).

  СЦЕНАРИЙ F — «Выход» из трея корректно завершает процесс:
    • Правый клик по трею → «Выход».
      ожидаемо: окно закрывается за < 2с; процесс полностью завершается
      (проверьте через Диспетчер задач — python.exe исчез).

Критерии приёмки (чек-лист):
  [ ] Overlay виден в правом верхнем углу, полупрозрачный, always-on-top
  [ ] Overlay обновляет состояние в реальном времени во время хода
  [ ] Overlay не перехватывает клики (click-through работает)
  [ ] Tray иконка появляется, правый клик — меню из 4 пунктов
  [ ] «Открыть папку сессии» открывает ~/Shura (или текущую) в Проводнике
  [ ] «Включить ассистента» из трея возвращает wake-word режим
  [ ] Ctrl+Alt+S включает wake-word, когда окно НЕ в фокусе
  [ ] «Выход» из трея завершает процесс за < 2с (Диспетчер задач пуст)
  [ ] Крестик окна всё ещё работает штатно (регрессия не внесена)

ПРИМЕЧАНИЕ: скрипт временный, удаляется после приёмки этапа пользователем.
"""

from __future__ import annotations

import logging
import sys

from bootstrap import bootstrap


def main() -> int:
    bootstrap()
    logging.getLogger().setLevel(logging.INFO)

    print(__doc__)
    try:
        input("Запустить GUI для приёмки? [Enter=да, Ctrl+C=выход] ")
    except (EOFError, KeyboardInterrupt):
        print()
        return 0

    # Sanity-check: все три модуля M8 импортируются без ошибок.
    from ui.hotkey import HotkeyListener  # noqa: F401
    from ui.overlay import Overlay  # noqa: F401
    from ui.tray import SystemTray  # noqa: F401
    from config import OVERLAY_ENABLED, TRAY_ENABLED, WAKE_HOTKEY
    print(
        f"M8 config: overlay={OVERLAY_ENABLED}, tray={TRAY_ENABLED}, "
        f"hotkey={WAKE_HOTKEY!r}"
    )

    # Делегируем на обычный запуск GUI (тот же, что `python main.py`).
    sys.argv = [sys.argv[0], "--mode", "ui"]
    import main as app_main
    return app_main.main()


if __name__ == "__main__":
    sys.exit(main())
