"""Этап M4: Pause/Resume через media keys + Mute/Unmute per-session +
Volume Up/Down — ручная приёмка.

Архитектура M4 (упрощение относительно изначального плана):
  • Pause/Resume → Win32 VK_MEDIA_PLAY_PAUSE (toggle для всех плееров,
    которые поддерживают media key API: YouTube в Яндекс.Браузере, VLC,
    MPC-HC и т.д.). Никаких HTTP API, никакой настройки пользователем.
  • Mute/Unmute → pycaw per-session: глушим все аудио-сессии Windows,
    КРОМЕ Шурочкиной (она продолжает говорить). На unmute снимаем mute
    с тех же сессий, что мы заглушили — не трогаем то, что пользователь
    приглушил сам.
  • Volume Up/Down → системные VK_VOLUME_UP/DOWN с привычным OSD.
    Громкость Шурочки масштабируется вместе со всем (мастер-регулятор).
  • Seek Forward/Backward → пока стабы (плеер-специфичный seek сложнее
    мастер-громкости и не приоритет).

Действия пользователя:

  СЦЕНАРИЙ A — Pause/Resume на YouTube в Яндекс.Браузере:
    • Откройте YouTube-видео в Яндекс.Браузере (можно в полноэкранном).
    • Скажите: «Шурочка, поставь паузу»
      Ожидаемо: видео встало; в консоли «⚡ выполнено как команда: pause»;
                голосом «поставила на паузу».
    • Скажите: «Шурочка, продолжи воспроизведение»
      Ожидаемо: видео идёт; голосом «продолжаю воспроизведение».

  СЦЕНАРИЙ B — Pause/Resume на VLC:
    • Запустите VLC с любым видео/аудио.
    • Скажите: «Шурочка, поставь паузу»
      Ожидаемо: VLC встал.
    • Скажите: «Шурочка, продолжи воспроизведение»
      Ожидаемо: VLC играет.

  СЦЕНАРИЙ C — Pause/Resume на MPC-HC (если используете):
    • Запустите MPC-HC, начните воспроизведение.
    • «Шурочка, поставь паузу» → пауза, «продолжи воспроизведение» → играет.
    • ВАЖНО: MPC должен быть в активной фокусе ИЛИ иметь включенные
      глобальные горячие клавиши. По умолчанию — обычно не работает,
      нужно проверить.

  СЦЕНАРИЙ D — Mute/Unmute (исключая Шурочку):
    • Запустите YouTube-видео (звук должен быть слышен).
    • Скажите: «Шурочка, выключи звук»
      Ожидаемо:
        - Видео онемело (но продолжает играть)
        - Шурочка озвучивает «выключила звук» — её слышно нормально
        - В консоли «🔇 Заглушено сессий: N»
    • Скажите: «Шурочка, ответь на вопрос столица Франции»
      Ожидаемо: ответ LLM прозвучит нормально, **YouTube остаётся muted**
    • Скажите: «Шурочка, включи звук»
      Ожидаемо:
        - YouTube снова со звуком
        - Голосом «включила звук»

  СЦЕНАРИЙ E — Volume Up/Down:
    • Скажите: «Шурочка, сделай громче»
      Ожидаемо:
        - Появляется системный OSD-индикатор Windows, громкость +10%
        - Голосом «прибавила громкости»
        - Шурочка тоже стала громче — это ожидаемо (мастер-громкость)
    • «Шурочка, сделай тише» → симметрично, -10%

  СЦЕНАРИЙ F — корректное снятие mute при выходе:
    • Снова заглушите чужой звук («выключи звук»).
    • НЕ снимая mute голосом, нажмите Ctrl+C.
    • Ожидаемо: при остановке pipeline в логах строка
      «unmute_others: снято N» — Шурочка убрала за собой, плеер снова
      со звуком после её выключения.

Критерии приёмки (чек-лист):
  [ ] Pause/Resume на YouTube в Яндекс.Браузере — работает
  [ ] Pause/Resume на VLC — работает
  [ ] Pause/Resume на MPC-HC — работает (или подтверждено, что нужны
      глобальные горячие клавиши, и они включены пользователем)
  [ ] Mute заглушает плеер, **Шурочку слышно**
  [ ] Unmute возвращает звук плееру
  [ ] При сценарии D «вопрос → ответ LLM» плеер остаётся muted
      (Шурочка не дёргает чужой mute случайно)
  [ ] Volume Up/Down даёт OSD-индикатор и заметное изменение
  [ ] При выходе через Ctrl+C при наличии заглушённых сессий — они
      разглушаются (проверить через системный микшер Windows)
  [ ] Ack-фразы играют корректно для всех 6 команд

ПРИМЕЧАНИЕ: скрипт временный, удаляется после приёмки этапа пользователем.
"""

from __future__ import annotations

import logging
import sys
import time

from bootstrap import bootstrap


def main() -> int:
    bootstrap()
    logging.getLogger().setLevel(logging.INFO)

    from main import VoicePipeline
    from core.wake_word import WakeWordListener

    print(__doc__)
    try:
        input("Поднять pipeline и начать? [Enter=да, Ctrl+C=выход] ")
    except (EOFError, KeyboardInterrupt):
        print()
        return 0

    pipeline = VoicePipeline()
    pipeline.start()

    listener = WakeWordListener(pipeline)
    listener.start()
    listener.enable()

    print("\n=== Готов, говорите. Ctrl+C — выход. ===\n")

    try:
        while True:
            time.sleep(0.5)
    except KeyboardInterrupt:
        print("\nCtrl+C — останавливаю…")
    finally:
        try:
            listener.stop()
        except Exception:
            logging.exception("listener.stop failed")
        pipeline.stop()

    print(__doc__.split("Критерии приёмки (чек-лист):")[1].split("ПРИМЕЧАНИЕ")[0])
    return 0


if __name__ == "__main__":
    sys.exit(main())
