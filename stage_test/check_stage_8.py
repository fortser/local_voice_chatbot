"""Этап 8: Wake-word активация («Шурочка») — ручная приёмка.

Что делает скрипт: запускает главное окно (ui.tkinter_ui.run_ui). После
того как статус-бар перейдёт в «🟢 Готов», можно тестировать новую кнопку
«🛌 Дежурный: выкл» и цикл активации по кодовому слову.

Действия пользователя:
  1. Запустите скрипт. После bootstrap() откроется окно. Подождите, пока
     статус не станет «🟢 Готов» (прогрев Whisper / Silero — 10–30 сек).
  2. Убедитесь, что **дежурный режим выключен по умолчанию** — кнопка
     подписана «🛌 Дежурный: выкл».
  3. Нажмите «🛌 Дежурный: выкл» — текст становится «🛌 Дежурный: вкл»,
     статус-бар показывает «🛌 Дежурный: жду «шурочка»».
  4. Произнесите «Шурочка» (одно слово). Ожидаемо:
       - Высокий бип (880 Гц, ~150 мс)
       - Статус: 👂 Услышал → 🎙 Слушаю вопрос
       - Задайте короткий вопрос голосом
       - Статус: 🧠 Обработка (дежурный) → услышите ответ ассистента
       - Возврат в «🛌 Дежурный: жду «шурочка»»
  5. Произнесите «Шурочка», затем замолчите на 10 секунд. Ожидаемо:
       - Высокий бип (активация)
       - Через 8 секунд низкий бип (400 Гц) — отмена по таймауту
       - Возврат в дежурный режим
  6. Произнесите любую фразу без слова «Шурочка» (например, «привет как
     дела»). Ожидаемо: нет бипа, нет активации, статус остаётся в
     дежурном. В логах видно строку «Wake-word scan: «привет как дела»
     (match=False)».
  7. Произнесите слово, похожее на wake, но не равное ему: «шурочкин»
     или «шурик». Ожидаемо: нет активации (защита от substring).
  8. Пока дежурный режим включён, нажмите ручную кнопку «🎤 Слушай».
     Ожидаемо: запись начинается (возможно, после небольшой задержки до
     4 сек — listener должен отпустить мьютекс). Полный цикл проходит
     нормально, после завершения дежурный режим продолжает работать.
  9. Нажмите «🛌 Дежурный: вкл» повторно — переходит в «выкл», статус
     возвращается в «🟢 Готов».
 10. Закройте окно — никаких зависаний, нет висящих тредов.

На что обращать внимание:
  * Бипы должны быть слышимыми, без щелчков на старте/концу (fade-out).
  * Статус в UI должен корректно переходить через все стадии.
  * Логи (фильтр INFO) — строки с «Wake-word scan: ... (match=...)»,
    «WakeWordListener started/stopped», «Standby mode enabled/disabled».
  * В дежурном режиме STT работает каждые ~4 секунды; это ожидаемо (MVP
    без отдельного wake-word движка). В logs/voice_ai.log это видно.

Ожидаемое время: 3–5 минут.

Критерии приёмки (чек-лист):
  [ ] Дежурный режим выключен по умолчанию (кнопка: «выкл»)
  [ ] Toggle включает/выключает; текст кнопки и статус-бар обновляются
  [ ] «Шурочка» → высокий бип → «Слушаю вопрос» → запись вопроса → ответ
  [ ] После ответа — возврат в «Дежурный: жду «шурочка»» без вмешательства
  [ ] «Шурочка» + 8с тишины → низкий бип → возврат в дежурный
  [ ] Фраза без кодового слова не активирует listener
  [ ] «шурочкин», «шурик» и прочие подстроки не активируют (false-positive защита)
  [ ] Ручная кнопка «🎤 Слушай» работает во время дежурного режима
  [ ] Закрытие окна останавливает listener без зависаний
  [ ] В logs/voice_ai.log видны записи «Wake-word scan: ... (match=...)»

ПРИМЕЧАНИЕ: скрипт временный, удаляется после приёмки этапа пользователем.
"""

from __future__ import annotations

import sys
import traceback


CHECKLIST = """
=== Чек-лист приёмки Stage 8 (Wake-word) ===
  [ ] Дежурный режим выключен по умолчанию
  [ ] Toggle включает/выключает; статус обновляется
  [ ] «Шурочка» → высокий бип → приём вопроса → ответ → возврат
  [ ] «Шурочка» + 8с тишины → низкий бип → возврат в дежурный
  [ ] Фраза без кодового слова не активирует
  [ ] «шурочкин», «шурик» не активируют (substring защита)
  [ ] Ручная «🎤 Слушай» работает во время дежурного
  [ ] Закрытие окна — нет зависаний
  [ ] Логи содержат «Wake-word scan: ... (match=...)»
"""


def main() -> int:
    print(__doc__)
    try:
        ans = input("Открыть окно? [Enter=да, n=нет] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return 0
    if ans == "n":
        return 0

    try:
        # Lazy import — тяжёлые зависимости подтягиваются только после
        # подтверждения пользователя.
        from ui.tkinter_ui import run_ui
        rc = run_ui()
    except Exception:
        print("\n!!! UI упал с исключением:")
        traceback.print_exc()
        rc = 1

    print(CHECKLIST)
    try:
        input("Все ли критерии выполнены? (y/n) — нажмите Enter, чтобы выйти. ")
    except (EOFError, KeyboardInterrupt):
        print()

    return rc


if __name__ == "__main__":
    sys.exit(main())
