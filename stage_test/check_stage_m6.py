"""Этап M6: Stop (голос) + Seek (next/prev track) + Cancel (Esc) — приёмка.

Архитектура M6:
  • StopCommand (голос) → выключает дежурный режим (wake_listener.disable()).
    Это НЕ выход из процесса; окно UI остаётся, можно снова включить
    дежурный режим кнопкой «🛌 Дежурный» или произнести wake-word и
    выполнить команду из обычного оборота.
  • SeekForward/Backward (голос) → VK_MEDIA_NEXT_TRACK / VK_MEDIA_PREV_TRACK.
    Это «следующий/предыдущий трек» для YouTube/Spotify/VLC. Универсальной
    системной клавиши «перемотать на N секунд» в Windows нет.
  • Cancel — клавишный, НЕ голосовой. В UI биндим <Escape>, он вызывает
    `pipeline.request_cancel()`, который сигналит cancel_event → VAD вылетает
    с CancelledError, играющий TTS → sd.stop() + CancelledError.
    Почему не голосом: синонимы «отмени/стоп» ловят ложные срабатывания
    Whisper'а и срывают диктовку/ответ — слишком дорого для комфорта.

Запуск этого скрипта запускает обычный UI через main.py (только в режиме
GUI, т.к. Esc живёт в Tk). Проверяйте сценарии в окне.

Действия пользователя:

  СЦЕНАРИЙ A — StopCommand выключает дежурный режим:
    • В UI нажмите «🛌 Дежурный: вкл».
    • Скажите: «Шурочка, закончи работу»
      Ожидаемо: голосом «закончила работу» (ack_after); в шапке UI
                дежурный режим выключился; WakeWordListener больше не
                сканирует (в логах нет «Wake-word scan»).
    • Убедитесь: окно живёт, можно снова включить «Дежурный» — всё работает.

  СЦЕНАРИЙ B — SeekForward/Backward на YouTube в Яндекс.Браузере:
    • Откройте плейлист на YouTube (или любой сайт с несколькими треками).
    • Скажите: «Шурочка, следующий трек» (или «перемотай вперёд»)
      Ожидаемо: YouTube переключается на следующее видео плейлиста;
                ack «перемотала вперёд».
    • Скажите: «Шурочка, предыдущий трек»
      Ожидаемо: возврат на предыдущее; ack «перемотала назад».
    • На одиночном видео без плейлиста команда всё равно шлёт keycode,
      но браузер её не обработает — это нормально (ожидаемое поведение
      системных media keys).

  СЦЕНАРИЙ C — Esc прерывает запись turn'а:
    • В UI нажмите «🎤 Слушай» (или скажите wake-word и дождитесь бипа).
    • Молчите 1-2 секунды и нажмите Esc на клавиатуре (окно UI должно
      быть в фокусе — биндинг bind_all).
      Ожидаемо: в консоли «⏹ отменено»; в логах «Turn cancelled during
                recording»; UI возвращается в idle, без STT/LLM прогона.

  СЦЕНАРИЙ D — Esc прерывает диктовку заметки:
    • Скажите: «Шурочка, запиши заметку».
    • После бипа начните диктовать («купить хлеб и…»), через секунду
      нажмите Esc.
      Ожидаемо: в консоли «⏹ диктовка отменена»; заметка НЕ сохранена
                (нет строк «✅ Заметка сохранена» / TTS-чтения).

  СЦЕНАРИЙ E — Esc прерывает играющий TTS-ответ:
    • Скажите: «Шурочка, ответь на вопрос расскажи про космос» (длинный
      ответ).
    • Когда Шурочка начнёт говорить — нажмите Esc.
      Ожидаемо: голос немедленно обрывается; в консоли «⏹ воспроизведение
                отменено»; UI возвращается в idle.

Критерии приёмки (чек-лист):
  [ ] «Закончи работу» голосом выключает дежурный режим (процесс живёт)
  [ ] После выключения можно снова включить дежурный режим кнопкой
  [ ] «Следующий трек» переключает YouTube-плейлист на следующее видео
  [ ] «Предыдущий трек» — симметрично
  [ ] Esc во время turn-recording отменяет оборот (нет STT/LLM)
  [ ] Esc во время диктовки отменяет заметку (нет save_note)
  [ ] Esc во время играющего TTS мгновенно обрывает воспроизведение
  [ ] Cancel-команды голосом НЕТ в registry (registry.names() без "cancel")
  [ ] Ack «закончи работу» играет корректно

ПРИМЕЧАНИЕ: скрипт временный, удаляется после приёмки этапа пользователем.
"""

from __future__ import annotations

import logging
import sys

from bootstrap import bootstrap


def main() -> int:
    bootstrap()
    logging.getLogger().setLevel(logging.INFO)

    print(__doc__)
    try:
        input("Запустить GUI для приёмки? [Enter=да, Ctrl+C=выход] ")
    except (EOFError, KeyboardInterrupt):
        print()
        return 0

    # Sanity-check: registry без CancelCommand.
    from commands.registry import build_default_registry
    names = build_default_registry().names()
    assert "cancel" not in names, f"CancelCommand всё ещё в registry: {names}"
    print(f"registry OK: {len(names)} команд, без cancel: {names}")

    # Делегируем на обычный запуск GUI (тот же, что `python main.py`).
    # main.main() парсит sys.argv; mode=ui — дефолт, так что достаточно вызвать.
    sys.argv = [sys.argv[0], "--mode", "ui"]
    import main as app_main
    return app_main.main()


if __name__ == "__main__":
    sys.exit(main())
