"""Этап 7: Tkinter UI с диагностикой — ручная приёмка.

Что делает скрипт: запускает главное окно приложения (ui.tkinter_ui.run_ui).
VoicePipeline + IPC-сервер инициализируются в фоне; как только статус-бар
перейдёт в "🟢 Готов", можно нажимать "🎤 Слушай", "🔄 Перекалибровать"
и смотреть полный цикл STT→LLM→TTS в UI.

Действия пользователя:
  1. Запустите скрипт. В консоли bootstrap() покажет выбранный вход/выход Windows.
  2. Нажмите Enter, чтобы открыть окно. Подождите, пока статус не станет "🟢 Готов"
     (обычно 10–30 сек — прогрев Whisper и Silero).
  3. Молчите во время первого статуса "🔵 Калибровка" — пайплайн сам калибруется.
  4. Убедитесь, что полоса RMS (Диагностика аудио) двигается в реальном времени,
     а синяя линия (шум) и красная пунктирная линия (порог) видны на шкале.
  5. Сразу после готовности в блоке "LLM модель" должен заполниться выпадающий
     список доступных моделей. Нажмите "🔄 Обновить" — список должен прийти
     из бэкенда (Ollama /api/tags или LM Studio /v1/models).
  6. Выберите модель из списка и нажмите "Применить" — под комбобоксом
     появится "✓ активна: <имя>".
  7. Нажмите "🎤 Слушай" → произнесите короткую фразу → проследите
     за сменой статусов: Запись → Обработка → Воспроизведение → Готов.
  8. Проверьте, что в поле "Вы:" появился распознанный текст, а в "Ассистент:" —
     ответ LLM. Услышите озвучку ответа.
  9. В блоке "Статистика оборота" должны появиться числа:
       🎤 Распознавание: N мс
       🧠 LLM: N мс  |  токены: prompt=..., completion=..., всего=...
       🔊 Синтез: N мс
       ⏱ Итого: N мс
     Если LLM-бэкенд не прислал токены (редко для Ollama), строка «токены» пропускается.
 10. Нажмите "🔄 Перекалибровать" (молчите 2 сек) — линии шума/порога должны
     обновиться.
 11. Во время обработки попробуйте двигать окно и скроллить логи — UI не должен
     зависать.
 12. (Опционально) остановите LM Studio / Ollama — в течение ~5 сек
     индикатор "LLM" станет 🔴.
 13. Закройте окно. Скрипт должен завершиться без зависаний.

На что обращать внимание:
  * В логах внутри окна видны записи компонентов (Whisper VRAM, LLM-тайминги,
     Silero длительность). Можно переключать фильтр INFO/WARNING/ERROR.
  * Сервисные пилюли: 🟢 Whisper (после load), 🟢 LLM (если бэкенд жив),
     TTS — 🟢 когда загружен, 🟡 (swap) если XTTS-на-CUDA и пайплайн его разгружает.
  * IPC: 🟢 если порт 9999 занялся, 🔴 если не поднялся (например, порт уже занят).

Ожидаемое время: 1–3 минуты (инициализация + несколько оборотов).

Критерии приёмки (чек-лист):
  [ ] Окно открывается; статус доходит до "🟢 Готов" без ошибок.
  [ ] Полоса RMS двигается в реальном времени при речи/тишине.
  [ ] Синяя линия (шум) и красная пунктирная линия (порог) видны и адекватны.
  [ ] Список моделей в комбобоксе заполняется после готовности; "Обновить"
       работает; "Применить" меняет активную модель (есть подтверждение).
  [ ] Нажатие "Слушай" запускает полный цикл, текст и ответ видны в окне,
       слышна озвучка.
  [ ] В блоке "Статистика оборота" после каждого цикла видны: мс для STT,
       LLM, TTS, итог; плюс токены (prompt/completion/всего), если бэкенд их прислал.
  [ ] Статус-бар проходит: Запись → Обработка → Воспроизведение → Готов.
  [ ] UI не фризится во время обработки — окно двигается, логи скроллятся.
  [ ] "Перекалибровать" пересчитывает шум/порог, числа в лейбле обновляются.
  [ ] При остановленной LLM индикатор становится 🔴 (≤ 5 сек).
  [ ] Закрытие окна завершает все потоки без зависаний, порт IPC освобождён.
  [ ] В logs/voice_ai.log зарегистрированы события каждого оборота.

ПРИМЕЧАНИЕ: скрипт временный, удаляется после приёмки этапа пользователем.
"""

from __future__ import annotations

import sys
import traceback


CHECKLIST = """
=== Чек-лист приёмки Stage 7 ===
  [ ] Окно открывается; статус доходит до "🟢 Готов"
  [ ] Полоса RMS двигается в реальном времени
  [ ] Синяя линия (шум) и красная линия (порог) видны
  [ ] Список моделей появляется; "Обновить" работает; "Применить" меняет модель
  [ ] "Слушай" → полный цикл, текст + ответ в окне, слышно озвучку
  [ ] Статистика оборота: STT/LLM/TTS/Итого в мс, токены LLM
  [ ] Статус-бар: Запись → Обработка → Воспроизведение → Готов
  [ ] UI не фризится во время обработки
  [ ] "Перекалибровать" обновляет шум/порог
  [ ] При остановленной LLM индикатор становится 🔴 (≤ 5 сек)
  [ ] Закрытие окна — нет зависаний, порт IPC свободен
  [ ] logs/voice_ai.log — события каждого оборота присутствуют
"""


def main() -> int:
    print(__doc__)
    try:
        ans = input("Открыть окно? [Enter=да, n=нет] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return 0
    if ans == "n":
        return 0

    try:
        # Lazy import — тяжёлые зависимости (tkinter + pipeline) подтягиваются
        # только после подтверждения пользователя.
        from ui.tkinter_ui import run_ui
        rc = run_ui()
    except Exception:
        print("\n!!! UI упал с исключением:")
        traceback.print_exc()
        rc = 1

    print(CHECKLIST)
    try:
        input("Все ли критерии выполнены? (y/n) — нажмите Enter, чтобы выйти. ")
    except (EOFError, KeyboardInterrupt):
        print()

    return rc


if __name__ == "__main__":
    sys.exit(main())
