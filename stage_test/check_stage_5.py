"""Этап 5: Интеграция pipeline (STT → LLM → TTS) — консольный режим.

Что делает скрипт: поднимает AudioStream + VAD + Whisper + LLM + TTS,
ведёт диалог в терминале — Enter → говоришь → слышишь ответ. Тот же
flow, что и `python main.py --mode console`, но с инструкциями и чек-листом
для ручной приёмки этапа.

Действия пользователя:
  1. Проверьте, что в шапке bootstrap()-а показаны нужные вход/выход
     (если нет — Параметры Windows → Система → Звук → Ввод/Вывод).
  2. Убедитесь, что LLM-бэкенд запущен:
        - LM Studio (по умолчанию): Developer → Local Server → Load Model,
          модель загружена и порт 1234 открыт;
        - либо Ollama: `ollama serve` + `ollama pull gemma-4-coder`.
  3. Дайте калибровке 2 сек тишины (ничего не говорите).
  4. Нажмите Enter → произнесите короткую фразу → дождитесь ответа.
  5. Повторите ≥5 оборотов подряд.

Edge cases, которые обязательно проверить:
  a. Молчание. Нажмите Enter, не говорите. Через ~30 сек запись оборвётся —
     должно прозвучать «Я не расслышал, повторите пожалуйста.» или сообщение
     об ошибке записи. Pipeline остаётся жив.
  b. Остановленный LLM. На середине сессии выключите LM Studio / Ollama,
     задайте вопрос — должно прозвучать «Возникла ошибка с языковой
     моделью.» Ошибка логируется в logs/voice_ai.log, процесс не падает.

На что обращать внимание:
  * Первый оборот — 10–25 сек (прогрев Whisper/LLM).
  * Последующие обороты — 3–10 сек (зависит от длины ответа LLM).
  * В синтезе НЕ должно быть слов из reasoning-блоков (если LLM thinking).
  * В консоли видны стадии: 🎤 → 📝 → 🧠 → 🔊.
  * logs/voice_ai.log содержит таймлайн каждого шага.

Выход: наберите `q` + Enter, либо Ctrl+C.

Критерии приёмки (чек-лист):
  [ ] Инициализация прошла без ошибок (калибровка, Whisper, LLM health, TTS).
  [ ] ≥5 оборотов "вопрос → ответ" подряд без крэша.
  [ ] Среднее время оборота после прогрева < 15 сек.
  [ ] Молчание → пользователь слышит fallback-фразу.
  [ ] Остановленный LLM → fallback про ошибку, pipeline остаётся жив.
  [ ] В озвучке нет reasoning-блоков (<think>).
  [ ] logs/voice_ai.log содержит записи каждого шага с таймингами.
  [ ] После выхода (`q`) — нет зависаний, микрофон/модели освобождены.

ПРИМЕЧАНИЕ: скрипт временный, удаляется после приёмки этапа пользователем.
"""

from __future__ import annotations

import sys

from main import run_console_mode


CHECKLIST = """
=== Чек-лист приёмки Stage 5 ===
  [ ] ≥5 оборотов прошли без крэша
  [ ] Среднее время оборота после прогрева < 15 сек
  [ ] Fallback на молчание работает (слышна фраза или корректная ошибка)
  [ ] Fallback на остановленный LLM работает (pipeline не падает)
  [ ] Reasoning-блоки НЕ попали в TTS (если модель thinking)
  [ ] logs/voice_ai.log содержит таймлайны шагов (stt, llm, tts)
  [ ] После выхода — нет зависших процессов / занятого микрофона
"""


def main() -> int:
    print(__doc__)
    try:
        ans = input("Продолжить? [Enter=да, n=нет] ").strip().lower()
    except (EOFError, KeyboardInterrupt):
        print()
        return 0
    if ans == "n":
        return 0

    try:
        run_console_mode()
    finally:
        print(CHECKLIST)
        try:
            input("Все ли критерии выполнены? (y/n) — нажмите Enter, чтобы выйти. ")
        except (EOFError, KeyboardInterrupt):
            print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
